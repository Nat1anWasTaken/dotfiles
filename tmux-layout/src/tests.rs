#[test]
fn column_layout_matches_python() {
    for &(width, height, count, large_left, want) in COLUMN_CASES {
        let panes: Vec<String> = (0..count).map(|i| (i * 3 + 1).to_string()).collect();
        let got = column_layout(width, height, &panes, large_left);
        let want = (!want.is_empty()).then(|| want.to_owned());
        assert_eq!(got, want, "{width}x{height} n={count} left={large_left}");
    }
}
